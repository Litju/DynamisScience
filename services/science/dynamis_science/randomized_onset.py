"""RES-716: prospective uniform onset allocation and finite-support sharp-null test."""
from __future__ import annotations

import copy
import html
import secrets
from datetime import datetime, timezone
from fractions import Fraction

from . import researchstore as store

DESIGN = 'RANDOMIZED_ONSET'
METHOD = 'METH-ONSET-EXACT'
NULL = 'Every scheduled outcome is identical under every permissible intervention onset (sharp null).'
LIMITS = [
    'Post-minus-pre mean is descriptive, not a validated causal magnitude; no confidence interval is supplied.',
    'Fixed time trends and serial dependence are retained in the exact assignment distribution; they can reduce sensitivity and distort the descriptive difference.',
    'One athlete and one randomized onset; no population inference, pooled athlete effect, physiological mechanism or forecast.',
    'Immediate-level statistic: delayed or gradual effects may be missed. Intervention persists; reversal and washout are not assumed.',
    'Requires no anticipation/interference, stable measurement and no assignment-dependent co-intervention or observation process.',
    'Failure to reject is not evidence of equivalence or absence of an effect. Separate athlete tests are not multiplicity-adjusted.',
]


def _date(value):
    try:
        result = datetime.fromisoformat(value)
        if result.tzinfo is None:
            raise ValueError
        return result
    except (ValueError, TypeError) as error:
        raise store.ResearchValidation('Schedule timestamps must be ISO dates/times with timezone') from error


def prepare(plan: dict, previous: list[dict]) -> dict:
    """Generate a draw only for a new prospective protocol, never accept a supplied draw."""
    if 'allocation' in plan:
        raise store.ResearchValidation('Allocation is generated by the app; historical or supplied draws are unsupported')
    schedule = plan.get('testing_occasions', [])
    starts = plan.get('permissible_starts', [])
    dates = plan.get('testing_dates', [])
    if (not 6 <= len(schedule) <= 5000 or any(type(v) is not int for v in schedule)
            or schedule != sorted(set(schedule))):
        raise store.ResearchValidation('Provide 6–5000 unique increasing integer scheduled occasions')
    if (not 2 <= len(starts) <= 1000 or any(type(v) is not int for v in starts)
            or starts != sorted(set(starts)) or any(v not in schedule or not 3 <= schedule.index(v) <= len(schedule)-3 for v in starts)):
        raise store.ResearchValidation('Provide 2–1000 unique increasing permitted starts, each leaving at least three baseline and three intervention sessions')
    if len(dates) != len(schedule):
        raise store.ResearchValidation('Provide one prespecified timestamp for every scheduled occasion')
    times = [_date(d) for d in dates]
    if any(a >= b for a, b in zip(times, times[1:])):
        raise store.ResearchValidation('Scheduled timestamps must be strictly increasing')
    for key in ('baseline_condition', 'intervention_condition', 'suitability'):
        if not str(plan.get(key, '')).strip():
            raise store.ResearchValidation(f'{key} is required for randomized onset')
    if plan['baseline_condition'].strip() == plan['intervention_condition'].strip():
        raise store.ResearchValidation('Baseline and intervention conditions must differ')
    if plan.get('assumptions_confirmed') is not True:
        raise store.ResearchValidation('Acknowledge no anticipation/interference, stable measurement and no assignment-dependent co-intervention or missingness')
    config = dict(testing_occasions=schedule, testing_dates=dates, permissible_starts=starts,
                  baseline_condition=plan['baseline_condition'].strip(), intervention_condition=plan['intervention_condition'].strip(),
                  assumptions_confirmed=True, statistic='ABS_POST_MINUS_PRE', alternative='TWO_SIDED', lag=0,
                  persistence='THROUGH_FINAL_VISIT', minimum_phase_sessions=3)
    if previous:
        old = previous[-1]
        allocation = old.get('allocation') or {}
        if old['design'] != DESIGN or allocation.get('configuration') != config:
            raise store.ResearchValidation('An existing investigation cannot be converted, redrawn or change its frozen allocation contract')
    else:
        if times[0] <= datetime.now(timezone.utc):
            raise store.ResearchValidation('All scheduled measurements must be future at allocation; never reconstruct historical randomization')
        allocation = dict(schema_version=1, mechanism='APP_SECRETS_UNIFORM_ONSET',
                          configuration=copy.deepcopy(config), assigned_start=secrets.choice(starts),
                          probability=1/len(starts), allocated_at=store._now(), id=f'ALLOC-{secrets.token_hex(8)}')
    start = allocation['assigned_start']
    return {**plan, 'allocation': copy.deepcopy(allocation), 'periods': [
        dict(kind='BASELINE', label=config['baseline_condition'], start=schedule[0], end=start-1),
        dict(kind='INTERVENTION', label=config['intervention_condition'], start=start, end=schedule[-1])],
        'assignment': f"App uniform draw {allocation['id']}: onset {start} from {starts}; probability 1/{len(starts)}"}


def evaluate(context: dict) -> dict:
    """Conservative eligibility receipt and exact calculation on a captured context."""
    data = context.get('timeline') or {}
    p = data.get('protocol') or {}
    a = p.get('allocation') or {}
    c = a.get('configuration') or {}
    issues = list(context.get('issues', []))
    if (p.get('design') != DESIGN or not p.get('prespecified') or a.get('mechanism') != 'APP_SECRETS_UNIFORM_ONSET'
            or a.get('schema_version') != 1 or not c.get('assumptions_confirmed')):
        issues.append('A saved app-generated prospective randomized-onset contract is required; free-text assignment is insufficient.')
    starts = c.get('permissible_starts', [])
    schedule = c.get('testing_occasions', [])
    if (not 2 <= len(starts) <= 1000 or any(type(s) is not int for s in starts) or starts != sorted(set(starts))
            or not 6 <= len(schedule) <= 5000 or any(type(s) is not int for s in schedule) or schedule != sorted(set(schedule))
            or a.get('assigned_start') not in starts or any(s not in schedule for s in starts) or schedule != p.get('testing_occasions')
            or len(c.get('testing_dates', [])) != len(schedule) or c.get('statistic') != 'ABS_POST_MINUS_PRE'
            or c.get('alternative') != 'TWO_SIDED' or c.get('lag') != 0 or c.get('persistence') != 'THROUGH_FINAL_VISIT'):
        issues.append('Allocation support, schedule or fixed analysis rule is incompatible.')
    try:
        allocated = _date(a.get('allocated_at'))
        dates = [_date(d) for d in c.get('testing_dates', [])]
        if any(d <= allocated for d in dates) or any(x >= y for x,y in zip(dates, dates[1:])):
            issues.append('All scheduled timestamps must increase and follow the prospective allocation.')
    except store.ResearchValidation as error:
        issues.append(str(error))
    if issues:
        return dict(status='NOT_QUALIFIED', issues=issues, p_value=None, limitations=LIMITS)
    rows = data['rows']
    if len(rows) != len(schedule) or any(r['status'] != 'MEASURED' or r['mean'] is None for r in rows):
        return dict(status='NOT_ESTIMABLE', issues=['Complete prespecified schedule required: planned, missing or nonfinite sessions cannot be imputed.'], p_value=None, limitations=LIMITS)
    import math
    for row, at, date in zip(rows, schedule, c['testing_dates']):
        v = row['visit']
        condition = 'BASELINE' if at < a['assigned_start'] else 'INTERVENTION'
        qc = v.get('qc') or {}
        if not math.isfinite(row['mean']) or qc.get('empty_values') or qc.get('quality_flags'):
            return dict(status='NOT_ESTIMABLE', issues=['Finite complete QC-eligible session measurements required; exclusions need scientific review.'], p_value=None, limitations=LIMITS)
        try:
            actual = _date(v['occurred_at'])
        except store.ResearchValidation as error:
            issues.append(str(error))
            continue
        if (row['scheduled_occasion'] != at or v['occasion'] != at or actual != _date(date)
                or actual <= allocated or v.get('actual_condition') != condition
                or v.get('deviations') or (condition == 'INTERVENTION' and v.get('adherence_percent') != 100)):
            issues.append('Recorded timing, condition, adherence or deviations violate the frozen allocation; inspect the visit ledger.')
    if issues:
        return dict(status='NOT_QUALIFIED', issues=sorted(set(issues)), p_value=None, limitations=LIMITS)
    values = [Fraction(str(r['mean'])) for r in rows]
    distribution = []
    contrasts = {}
    for start in starts:
        index = schedule.index(start)
        if not 3 <= index <= len(values)-3:
            return dict(status='NOT_QUALIFIED', issues=['Every permissible onset requires at least three sessions in each phase.'], p_value=None, limitations=LIMITS)
        difference = sum(values[index:])/len(values[index:]) - sum(values[:index])/index
        contrasts[start] = difference
        distribution.append(dict(start=start, statistic=float(abs(difference)), exact_statistic=str(abs(difference))))
    observed = abs(contrasts[a['assigned_start']])
    extreme = sum(abs(v) >= observed for v in contrasts.values())
    return dict(status='QUALIFIED', issues=[], null_hypothesis=NULL, statistic=float(observed),
                statistic_name='Absolute post-minus-pre session mean', alternative='TWO_SIDED',
                descriptive_difference=float(contrasts[a['assigned_start']]), p_value=extreme/len(starts),
                tail_count=extreme, assignment_count=len(starts), p_resolution=1/len(starts),
                distribution=distribution, assigned_start=a['assigned_start'],
                limitations=[*LIMITS, *(['Support too small to attain p ≤ 0.05.'] if len(starts)<20 else [])])


def eligibility(method, metric, subjects, scope, parameters, context):
    context = context or {'issues': ['Experimental protocol and visit context required.']}
    receipt = evaluate(context)
    p = (context.get('timeline') or {}).get('protocol') or {}
    issues = list(receipt['issues'])
    if scope.get('kind') != 'INDIVIDUAL' or subjects != [p.get('subject_id')]:
        issues.append('Exactly one pinned athlete investigation is required; pooling is unsupported.')
    if metric['id'] != p.get('outcome_metric_id') or metric.get('unit') != p.get('unit') or metric['table'] not in method['required_tables']:
        issues.append('Selected outcome and units must match the randomized protocol.')
    if set(parameters) - {'protocol_version'}:
        issues.append('Only protocol_version is accepted; statistic, tail and support are frozen before allocation.')
    return {**copy.deepcopy(method), 'method_id': METHOD, 'status': 'INELIGIBLE' if issues else 'ELIGIBLE',
            'issues': issues, 'inference_status': receipt['status'] if receipt['issues'] else ('NOT_QUALIFIED' if issues else 'QUALIFIED'),
            'protocol_version': p.get('version'), 'population': {'subjects': len(subjects)}, 'limitations': receipt['limitations']}


def execute(context):
    from .experiments import describe
    result = describe(context)  # Retain the existing ledger, phase descriptions and plot contract.
    receipt = evaluate(context)
    result.update(method='Exact randomized intervention-onset test', inference_status=receipt['status'],
                  inference=receipt, limitations=receipt['limitations'])
    return result


def result_html(result, *, chart=False):
    from .experiments import result_html as descriptions
    r = result['inference']
    esc = lambda v: html.escape(str(v))
    a = result['protocol']['allocation']
    body = (f"<h3>Exact randomized onset · {esc(r['status'])}</h3><p><b>Null hypothesis:</b> {esc(NULL)}</p>"
            f"<p>Allocation {esc(a['id'])} · onset {a['assigned_start']} · drawn {esc(a['allocated_at'])}<br>"
            f"Permitted starts: {esc(a['configuration']['permissible_starts'])}</p>")
    if r['p_value'] is not None:
        body += (f"<p>Descriptive post-minus-pre difference: <b>{r['descriptive_difference']:.6g} {esc(result['unit'])}</b> (no causal interval).<br>"
                 f"Two-sided exact p = <b>{r['tail_count']}/{r['assignment_count']} = {r['p_value']:.6g}</b>; "
                 f"resolution {r['p_resolution']:.6g}; statistic |post mean − pre mean| = {r['statistic']:.6g}.</p>"
                 f"<p>Tail rule: {r['tail_count']} of {r['assignment_count']} permitted onsets have "
                 'an absolute difference greater than or equal to the observed absolute difference. '
                 'Ties and the observed allocation are included; both directions count. '
                 'This is an absolute-statistic tail, not twice a one-sided p-value. '
                 f"Minimum attainable p = 1/{r['assignment_count']}; ties can make it larger.</p>"
                 '<p>The p-value is the probability under the sharp null and saved assignment mechanism of a statistic at least this extreme. It is not the probability that the null is true. This does not establish a causal effect magnitude.</p>')
    else:
        body += '<p>' + esc('; '.join(r['issues'])) + '</p>'
    return body + descriptions(result, chart=chart)
